// thực hiện các phép tính
let a = 10;
let b = 3;
console.log(a + b);   // 13   (cộng)
console.log(a - b);   // 7    (trừ)
console.log(a * b);   // 30   (nhân)
console.log(a / b);   // 3.3333333333333335 (chia)
console.log(a % b);   // 1    (chia lấy dư)
console.log(a ** b);  // 1000 (lũy thừa)